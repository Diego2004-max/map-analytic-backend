import cors from 'cors'; import dotenv from 'dotenv'; import express from 'express';
import { dbPool, initializeDatabase } from './config/database.js';
import { ReportController } from './controllers/report.controller.js';
import { NLPClassificationService } from './services/nlp-classification.service.js';
import { AnomalyMonitorService } from './services/anomaly-monitor.service.js';
dotenv.config();
const app = express(); const port = Number(process.env.PORT || 5000);
const origins = (process.env.FRONTEND_ORIGIN || 'http://localhost:3000').split(',').map((value) => value.trim());
app.use(cors({ origin: origins })); app.use(express.json({ limit: '32kb' }));
const reports = new ReportController(new NLPClassificationService()); const monitor = new AnomalyMonitorService();
app.post('/api/v1/reports', reports.createReport); app.get('/api/v1/reports', reports.getReports);
app.post('/api/reports', reports.createReport); app.get('/api/reports', reports.getReports);
app.get('/api/health', async (_req, res, next) => { try { await dbPool.query('SELECT 1'); res.json({ status: 'ok', timestamp: new Date().toISOString() }); } catch (error) { next(error); } });
const scan = async (_req, res, next) => { try { res.json({ success: true, data: await monitor.scanTerritorialAnomalies() }); } catch (error) { next(error); } };
app.get('/api/v1/monitor/scan', scan); app.get('/api/monitor/scan', scan);
app.use((error, _req, res, _next) => { console.error('[API]', error); res.status(500).json({ error: 'Unexpected server error.' }); });
initializeDatabase().then(() => app.listen(port, () => console.log(`[MapAnalytic Server] Running on port ${port}`))).catch((error) => { console.error('[Startup]', error); process.exitCode = 1; });
